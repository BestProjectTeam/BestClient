constexpr int GLYPH_COLS = 5;
constexpr int GLYPH_ROWS = 7;
constexpr int GLYPH_GAP = 1;

inline const unsigned char *FindGlyph(char Char)
{
	for(const SGlyph &Glyph : g_aGlyphs)
	{
		if(Glyph.m_Char == Char)
			return Glyph.m_aCol;
	}
	return g_aGlyphs[0].m_aCol; // space
}

inline int TextWidth(const char *pText, int Scale)
{
	const int Len = (int)strlen(pText);
	if(Len == 0)
		return 0;
	return Len * (GLYPH_COLS + GLYPH_GAP) * Scale - GLYPH_GAP * Scale;
}

inline void DrawText(SDL_Renderer *pRenderer, int X, int Y, int Scale, const char *pText, SDL_Color Color)
{
	SDL_SetRenderDrawColor(pRenderer, Color.r, Color.g, Color.b, Color.a);
	int CursorX = X;
	for(const char *p = pText; *p != '\0'; ++p)
	{
		const unsigned char *pCol = FindGlyph(*p);
		for(int Col = 0; Col < GLYPH_COLS; ++Col)
		{
			for(int Row = 0; Row < GLYPH_ROWS; ++Row)
			{
				if(pCol[Col] & (1 << Row))
				{
					SDL_Rect Px = {CursorX + Col * Scale, Y + Row * Scale, Scale, Scale};
					SDL_RenderFillRect(pRenderer, &Px);
				}
			}
		}
		CursorX += (GLYPH_COLS + GLYPH_GAP) * Scale;
	}
}

